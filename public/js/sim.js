export function simReply(agentId, prompt, brief = '') {
  const topic = topicOf(prompt);
  return (REPLIES[agentId] || REPLIES.tenx)(topic, slug(topic), brief);
}

/** Stream text in small, uneven chunks. Resolves when done; rejects with AbortError if aborted. */
export function streamSim(text, onText, signal, { delay = 28 } = {}) {
  return new Promise((resolve, reject) => {
    let i = 0;
    const abort = () => { clearTimeout(timer); reject(new DOMException('Aborted', 'AbortError')); };
    if (signal?.aborted) return abort();
    signal?.addEventListener('abort', abort, { once: true });
    let timer;
    const tick = () => {
      if (i >= text.length) { signal?.removeEventListener('abort', abort); resolve(); return; }
      const n = 3 + Math.floor(Math.random() * 9);
      onText(text.slice(i, i + n));
      i += n;
      timer = setTimeout(tick, delay);
    };
    timer = setTimeout(tick, 350); // a moment of "thinking"
  });
}
