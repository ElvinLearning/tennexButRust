// Offline "Sim" mode: canned replies in the real reply format, streamed in small chunks.

function topicOf(prompt) {
  const t = prompt
    .replace(/^(please|can you|could you|would you|let's|lets|i want you to|i need you to)\s+/i, '')
    .replace(/[?.!]+$/, '')
    .trim();
  return t.length > 70 ? `${t.slice(0, 70)}…` : t || 'this';
}

function slug(topic) {
  return topic.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '').slice(0, 28) || 'feature';
}

